const langButtons = document.querySelectorAll('.lang-btn');
const i18nElements = document.querySelectorAll('[data-i18n]');
const supportedLanguages = ['en', 'pt', 'fr'];
const storageKey = 'noverix-language';

function renderSentenceLines(element, text) {
  const sentences = text.match(/[^.!?]+[.!?]+|[^.!?]+$/g)?.map((part) => part.trim()) || [text];
  element.innerHTML = '';
  sentences.forEach((sentence) => {
    const line = document.createElement('span');
    line.className = 'hero-title-line';
    line.textContent = sentence;
    element.appendChild(line);
  });
}

function getInitialLanguage() {
  try {
    const savedLanguage = window.localStorage.getItem(storageKey);
    if (supportedLanguages.includes(savedLanguage)) return savedLanguage;
  } catch {}
  const browserLanguage = navigator.language.slice(0, 2).toLowerCase();
  if (supportedLanguages.includes(browserLanguage)) return browserLanguage;
  return 'pt';
}

function applyLanguage(lang) {
  const selected = translations[lang] || translations.en;
  i18nElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(selected, key)) {
      if (key === 'heroTitle') {
        renderSentenceLines(element, selected[key]);
      } else {
        element.textContent = selected[key];
      }
    }
  });
  document.documentElement.lang = lang;
  langButtons.forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
  try { window.localStorage.setItem(storageKey, lang); } catch {}
}

langButtons.forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang));
});

document.getElementById('year').textContent = new Date().getFullYear();
applyLanguage(getInitialLanguage());

// === AVELIX APP CAROUSEL ===
(function () {
  let cur = 0;
  const slides = document.querySelectorAll('.app-slide');
  const dots = document.querySelectorAll('.app-dot');
  if (!slides.length) return;

  window.appGoTo = function (n) {
    slides[cur].classList.remove('active');
    dots[cur].classList.remove('active');
    cur = n;
    slides[cur].classList.add('active');
    dots[cur].classList.add('active');
  };

  setInterval(() => window.appGoTo((cur + 1) % slides.length), 2800);
})();
